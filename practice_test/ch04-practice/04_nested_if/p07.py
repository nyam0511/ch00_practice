"""
실습 7: 영화 추천
"""

# 장르 (액션/로맨스) 입력받기
genre = input("장르를 입력하세요 (액션/로맨스): ")
# 나이 입력받기
age = int(input("나이를 입력하세요: "))

# 장르가 액션이면
if genre == "액션":
    # 나이가 19세 이상: "추천: 존 윅"
    if age >= 19:
        print("추천: 존 윅")
    # 나이가 19세 미만: "추천: 스파이더맨"
    else:
        print("추천: 스파이더맨")
# 장르가 로맨스이면
elif genre == "로맨스":
    # 나이가 19세 이상: "추천: 노트북"
    if age >= 19:
        print("추천: 노트북")
    # 나이가 19세 미만: "추천: 너의 이름은"
    else:
        print("추천: 너의 이름은")
# 그 외 장르: "해당 장르의 추천 영화가 없습니다."
else:
    print("해당 장르의 추천 영화가 없습니다.")