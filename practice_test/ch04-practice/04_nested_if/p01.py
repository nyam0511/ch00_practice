"""
실습 1: 입장 판정
"""

# 나이 입력받기
age = int(input("나이를 입력하세요: "))
# 티켓 여부 입력받기
ticket = input("티켓이 있나요? (Y/N): ")

# 나이가 18세 이상이면
if age >= 18:
    # 티켓이 Y이면 "입장 가능합니다."
    if ticket == "Y":
        print("입장 가능합니다.")
    # 티켓이 N이면 "티켓을 구매해주세요."
    else:
        print("티켓을 구매해주세요.")
# 나이가 18세 미만이면 "18세 미만은 입장할 수 없습니다."
else:
    print("18세 미만은 입장할 수 없습니다.")