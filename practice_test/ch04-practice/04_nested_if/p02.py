"""
실습 2: 로그인 시스템

정답 아이디: "admin"
정답 비밀번호: "1234"
"""

# 아이디 입력받기
user_id = input("아이디를 입력하세요: ")
# 비밀번호 입력받기
password = input("비밀번호를 입력하세요: ")

# 아이디가 맞으면
if user_id == "admin":
    # 비밀번호가 맞으면 "로그인 성공!"
    if password == "1234":
        print("로그인 성공!")
    # 비밀번호가 틀리면 "비밀번호가 틀렸습니다."
    else:
        print("비밀번호가 틀렸습니다.")
# 아이디가 틀리면 "ID가 존재하지 않습니다."
else:
    print("ID가 존재하지 않습니다.")