"""
실습 8: 온도별 옷차림 추천
"""

# 기온 입력받기
temp = float(input("현재 기온을 입력하세요 (°C): "))

# 5도 미만: 패딩, 두꺼운 목도리
if temp < 5:
    dress = "패딩, 두꺼운 목도리"
# 5도 이상 10도 미만: 코트, 니트
elif temp < 10:
    dress = "코트, 니트"
# 10도 이상 20도 미만: 자켓, 가디건
elif temp < 20:
    dress = "자켓, 가디건"
# 20도 이상 28도 미만: 반팔, 얇은 셔츠
elif temp < 28:
    dress = "반팔, 얇은 셔츠"
# 28도 이상: 민소매, 반바지
else:
    dress = "민소매, 반바지"

# 현재 기온 출력
print("현재 기온:", str(temp) + "°C")
# 추천 옷차림 출력
print("추천 옷차림:", dress)