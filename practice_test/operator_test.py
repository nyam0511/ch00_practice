# 정수 두 개를 입력 받기
# 첫 번째 수 입력 받기
num1 = int(input("첫 번째 수: "))

# 두 번째 수 입력 받기
num2 = int(input("두 번째 수: "))

# 덧셈 결과 
print(num1 + num2)
# 뺄셈 결과
print(num1 - num2)
# 곱셈 결과
print(num1 * num2)
# 나눗셈 결과
print(num1 / num2)
# 몫
print(num1 // num2)
# 나머지
print(num1 % num2)
# 첫 번째 수의 두 번째 수 제곱값
print(num1 ** num2)