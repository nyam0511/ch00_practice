"""
실습 1: 간단한 계산기
"""
# 두 수를 입력받아 사칙연산(+ - * /) 결과 모두 출력

# 첫 번째 수 입력받기
a = int(input("첫 번째 수: "))

# 두 번째 수 입력받기
b = int(input("두 번째 수: "))

# 더하기
print("더하기:", a + b)
# 빼기
print(f"빼기: {a - b}")
# 곱하기
print("곱하기:", a * b)
# 나누기
print("나누기:", a / b)
# 몫
print("몫:", a // b)
# 나머지
print("나머지:", a % b)
# 거듭제곱
print("거듭제곱:", a ** b)